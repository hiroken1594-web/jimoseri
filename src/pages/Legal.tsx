// 利用規約・プライバシーポリシーの文案。
// 一般公開の前に、運営者情報の設定と、内容の確認（大学の担当部署や専門家）が必要。

function OperatorBlock() {
  const { master } = useSession()
  if (!master.operator) {
    return (
      <Notice kind="warn" title="準備中">
        <p>運営者情報が未設定のため、この文書は確定していません。運営者情報と内容の確認が整うまで、一般の方の新規登録は受け付けません。</p>
      </Notice>
    )
  }
  return (
    <p>
      運営者：{master.operator.name}
      <br />
      お問い合わせ：{master.operator.email}
    </p>
  )
}

